"""Valuation models: DCF and multiple-based, both deterministic.

A stock pitch without a price target and an implied upside is not a pitch.
The UPenn reference deck leads with "Pitched Price $24.05 | Target $33.27 |
Implied Upside 38.3%" and devotes a slide to methodology, cases and a
sensitivity grid.

Producing that requires forward estimates, which collides with the rule that
governs the rest of this project: no figure may be generated by a model. The
resolution is that a DCF is not a forecast asserted as fact, it is arithmetic
over assumptions. So:

- Every assumption is an explicit, named, editable input with a stated basis.
- The arithmetic runs here, in Python, and is reproducible.
- A sensitivity grid shows how the output moves across the two assumptions it
  is most exposed to, which is the honest way to present a number that
  depends on judgement.
- Historical inputs (revenue, margins, capex, working capital) come from
  filed XBRL, not from a model.

An analyst can disagree with an assumption and change it. They cannot
disagree with a number that appeared from nowhere, which is why the previous
version of this tool refused to produce one at all.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date

from asset_researcher.quant.capital import net_debt
from asset_researcher.quant.series import MetricSeries

# Non-meaningful, the convention in published comps tables for a ratio whose
# denominator is negative or near zero.
NM = "NM"


@dataclass(frozen=True)
class Assumption:
    """One model input, with the basis a reviewer needs to challenge it."""

    name: str
    value: float
    unit: str  # "%", "x", "years", "$"
    basis: str  # where the number came from
    editable: bool = True

    def display(self) -> str:
        """The value with its unit.

        A dollar figure is scaled: "$105,493,070,000" is twelve digits a
        reader has to count, and the model is not precise to the dollar. A
        horizon printed as "10.0" with the word "years" living only in the
        row label is a number without a unit.
        """
        if self.unit == "%":
            return f"{self.value * 100:.1f}%"
        if self.unit == "x":
            return f"{self.value:.1f}x"
        if self.unit == "$":
            # Parentheses for negatives, as everywhere else in the report. A
            # net-cash position printed "$-33.8B" beside a statement row
            # reading "(33,763)" for the same figure.
            magnitude = abs(self.value)
            if magnitude >= 1e9:
                rendered = f"${magnitude / 1e9:,.1f}B"
            elif magnitude >= 1e6:
                rendered = f"${magnitude / 1e6:,.1f}M"
            else:
                rendered = f"${magnitude:,.0f}"
            return f"({rendered})" if self.value < 0 else rendered
        if self.unit == "shares":
            return f"{self.value / 1e6:,.0f}M"
        if self.unit == "years":
            return f"{self.value:,.0f} years"
        return f"{self.value:,.1f}"


@dataclass
class DcfInputs:
    """Assumptions driving the discounted cash flow.

    Defaults are derived from the company's own filed history wherever
    possible. Where no filed basis exists (discount rate, terminal growth),
    the default is a conventional starting point and is labelled as such, not
    presented as a finding.
    """

    base_fcf: float
    fcf_growth: float
    discount_rate: float
    terminal_growth: float
    forecast_years: int
    net_debt: float
    shares_outstanding: float
    basis: dict[str, str] = field(default_factory=dict)

    def assumptions(self) -> list[Assumption]:
        """Every input the model actually reads, with its basis.

        Three of these were missing and one was inert. `base_fcf`, `net_debt`
        and `shares_outstanding` set the answer as directly as the growth
        rate does, and omitting them left a reviewer unable to check the
        figure they most wanted to check. A "free cash flow margin" row was
        shown with a stated basis and never read by `run_dcf`, so a reviewer
        who disagreed with it and changed it changed nothing, which is worse
        than not showing it at all.

        The growth driver is named for what it grows. It is applied to free
        cash flow, not to revenue, which holds the cash margin flat by
        construction; calling it "revenue growth" hid that assumption.
        """
        return [
            Assumption("Base free cash flow", self.base_fcf, "$",
                       self.basis.get("base_fcf", "")),
            Assumption("Free cash flow growth (annual)", self.fcf_growth, "%",
                       self.basis.get("fcf_growth", "")),
            Assumption("Discount rate (WACC)", self.discount_rate, "%",
                       self.basis.get("discount_rate", "")),
            Assumption("Terminal growth", self.terminal_growth, "%",
                       self.basis.get("terminal_growth", "")),
            Assumption("Forecast horizon", float(self.forecast_years), "years",
                       self.basis.get("forecast_years", "")),
            Assumption("Net debt", self.net_debt, "$",
                       self.basis.get("net_debt", "")),
            Assumption("Diluted shares outstanding", self.shares_outstanding,
                       "shares", self.basis.get("shares_outstanding", "")),
        ]


@dataclass(frozen=True)
class DcfResult:
    enterprise_value: float
    equity_value: float
    value_per_share: float
    pv_forecast: float
    pv_terminal: float
    projected_fcf: list[tuple[int, float, float]]  # (year, fcf, discounted fcf)

    @property
    def terminal_share_of_value(self) -> float:
        """How much of the valuation rests on the terminal assumption.

        Above roughly 75% the answer is mostly a statement about perpetuity
        growth rather than about the forecast, and a reviewer should be told
        that plainly.
        """
        total = self.pv_forecast + self.pv_terminal
        return self.pv_terminal / total if total else 0.0


def run_dcf(inputs: DcfInputs) -> DcfResult:
    """Standard single-stage DCF with a Gordon growth terminal value."""
    if inputs.discount_rate <= inputs.terminal_growth:
        raise ValueError(
            "Discount rate must exceed terminal growth, otherwise the "
            "terminal value is infinite."
        )

    projected: list[tuple[int, float, float]] = []
    pv_forecast = 0.0
    fcf = inputs.base_fcf

    for year in range(1, inputs.forecast_years + 1):
        fcf = fcf * (1 + inputs.fcf_growth)
        discounted = fcf / ((1 + inputs.discount_rate) ** year)
        pv_forecast += discounted
        projected.append((year, fcf, discounted))

    terminal_fcf = fcf * (1 + inputs.terminal_growth)
    terminal_value = terminal_fcf / (inputs.discount_rate - inputs.terminal_growth)
    pv_terminal = terminal_value / ((1 + inputs.discount_rate) ** inputs.forecast_years)

    enterprise_value = pv_forecast + pv_terminal
    equity_value = enterprise_value - inputs.net_debt
    if inputs.shares_outstanding <= 0:
        # Zero returned a $0.00 value per share and a -100% upside, both
        # presented as findings; a negative count returned a trillion-dollar
        # negative. The discount-rate guard above refuses on the same
        # grounds, and so does this.
        raise ValueError(
            "Shares outstanding must be positive to compute a value per "
            "share."
        )
    per_share = equity_value / inputs.shares_outstanding

    return DcfResult(
        enterprise_value=enterprise_value,
        equity_value=equity_value,
        value_per_share=per_share,
        pv_forecast=pv_forecast,
        pv_terminal=pv_terminal,
        projected_fcf=projected,
    )


def sensitivity_grid(
    inputs: DcfInputs,
    discount_rates: list[float],
    terminal_growths: list[float],
) -> list[dict[str, str]]:
    """Value per share across discount rate and terminal growth.

    These are the two assumptions a DCF is most exposed to and the two a
    reviewer will push on first, which is why every published valuation
    slide carries this grid rather than a single number.
    """
    rows = []
    for rate in discount_rates:
        row = {"WACC": f"{rate * 100:.1f}%"}
        for growth in terminal_growths:
            label = f"{growth * 100:.1f}%"
            if rate <= growth:
                row[label] = NM
                continue
            variant = DcfInputs(**{**inputs.__dict__, "discount_rate": rate,
                                   "terminal_growth": growth})
            row[label] = f"${run_dcf(variant).value_per_share:,.2f}"
        rows.append(row)
    return rows


def _latest(series: MetricSeries, metric: str) -> float | None:
    points = series.series.get(metric)
    return points[-1].value if points else None


def _cagr(series: MetricSeries, metric: str) -> tuple[float, int] | None:
    """Compound annual growth, with the number of years it spans.

    The span is returned rather than inferred by the caller because it is
    one less than the number of filed periods, and an assumptions table that
    described a four-year CAGR as a five-year one was describing the model
    inaccurately in the one place built for checking it.
    """
    points = series.series.get(metric) or []
    if len(points) < 2:
        return None
    first, last = points[0].value, points[-1].value
    if first <= 0 or last <= 0:
        return None
    years = _elapsed_years(points[0].end, points[-1].end)
    if years is None:
        return None
    return (last / first) ** (1 / years) - 1, round(years)


def _elapsed_years(first_end: str, last_end: str) -> float | None:
    """Years between two period ends, from the dates themselves.

    Counting observations instead assumes the series has no holes. With a
    missing middle year, 100 in FY2020 and 121 in FY2022 was read as one
    step and reported as 21% annual growth where the true rate is 10%. The
    cap applied downstream hid the magnitude without fixing the arithmetic.
    """
    try:
        start = date.fromisoformat(first_end)
        end = date.fromisoformat(last_end)
    except ValueError:
        return None
    years = (end - start).days / 365.25
    return years if years >= 0.5 else None


def free_cash_flow_history(series: MetricSeries) -> list[tuple[str, str, float]]:
    """(period end, label, free cash flow) for every year both lines are filed.

    A year in which capital expenditure is not tagged is omitted rather than
    treated as a year of zero capex. Defaulting it to zero turned free cash
    flow into operating cash flow for that year and said nothing: on a filer
    tagging capex in only the latest of three years it overstated the base by
    13% and produced a free cash flow growth rate that was purely an artefact
    of the tagging gap.

    Periods are keyed on the end date rather than the display label, because
    a label is a presentation detail and two periods can legitimately share
    one before disambiguation.
    """
    capex = {
        p.end: abs(p.value)
        for p in (series.series.get("capital_expenditures") or [])
    }
    return [
        (p.end, p.frame_label, p.value - capex[p.end])
        for p in (series.series.get("operating_cash_flow") or [])
        if p.end in capex
    ]


def normalised_base_fcf(series: MetricSeries, window: int = 3) -> float | None:
    """Mean free cash flow over the recent window, not the latest year.

    A single year sets the base for the entire model, so a year distorted by
    working capital timing propagates through every projected period.
    Measured on Apple: FY2025 free cash flow of $98.8B is below FY2022's
    $111.4B, largely on a receivables build the report separately flags. The
    three-year mean of $102.4B is the more defensible starting point.

    Every year in the window counts. An earlier version dropped the negative
    ones before averaging, which is not an average: on operating cash flow of
    (-10, +5, +6) billion against 1 billion of capex a year it returned
    +$4.5B where the mean is -$0.7B. That filter was also the only thing
    standing between a cash-burning filer and a confident discounted cash
    flow, because the caller refuses to build one on a non-positive base.
    """
    history = free_cash_flow_history(series)
    if not history:
        return None
    recent = [value for _, _, value in history[-window:]]
    return sum(recent) / len(recent)


# A statutory rate, used only to unlever interest. It is a convention, and
# the assumptions table says so; deriving an effective rate would need a tax
# expense line that many filers do not tag consistently.
_UNLEVERING_TAX_RATE = 0.21


def _unlever(series: MetricSeries, base_fcf: float) -> tuple[float, str]:
    """Free cash flow before the cost of debt, with the basis used.

    Operating cash flow is reported after interest paid and after tax, so
    operating cash flow less capital expenditure is a levered figure. The
    model discounts it at a weighted average cost of capital and then
    subtracts net debt, which charges the debt claim twice.

    Adding back after-tax interest expense produces the unlevered figure the
    enterprise-to-equity bridge expects. Where the filer does not tag
    interest expense, no add-back is possible and the convention is disclosed
    rather than applied silently.
    """
    # The interest must belong to the window the base cash flow came from.
    # `_latest` returns the last period the metric has *any* value for, and
    # Apple stopped tagging interest expense after FY2023, so an FY2023
    # figure was being added back to a base normalised over FY2023 to
    # FY2025: a period mismatch inside an adjustment meant to make the
    # arithmetic consistent.
    cash_periods = {end for end, _, _ in free_cash_flow_history(series)[-3:]}
    interest_points = series.series.get("interest_expense") or []
    recent = [p.value for p in interest_points if p.end in cash_periods]
    interest = recent[-1] if recent else None

    if not interest or interest <= 0:
        return base_fcf, (
            "Three-year average of filed operating cash flow less capital "
            "expenditure. This filer does not tag interest expense over the "
            "same period, so no add-back was made and the figure remains "
            "levered; the bridge below therefore charges debt once through "
            "the cash flow and again through net debt"
        )
    add_back = interest * (1 - _UNLEVERING_TAX_RATE)
    return base_fcf + add_back, (
        "Three-year average of filed operating cash flow less capital "
        f"expenditure, plus filed interest expense after tax at "
        f"{_UNLEVERING_TAX_RATE:.0%}. The add-back unlevers the cash flow so "
        "that discounting at a weighted average cost of capital and then "
        "deducting net debt does not charge the debt claim twice"
    )


# Sector classes whose economics this enterprise model does not describe.
# Named here rather than inline so the exclusion is one fact in one place.
_NO_ENTERPRISE_DCF = frozenset({"financial", "reit"})


def derive_dcf_inputs(
    series: MetricSeries,
    shares_outstanding: float | None,
    discount_rate: float = 0.085,
    terminal_growth: float = 0.025,
    forecast_years: int = 10,
    sector_class: str = "standard",
) -> DcfInputs | None:
    """Build a starting set of assumptions from the company's filed history.

    Returns None when the filings do not support a cash flow model, which is
    the correct outcome for a filer whose statements do not fit this shape.
    Defaults are a starting point for the analyst to overwrite, not a view.
    """
    operating_cash_flow = _latest(series, "operating_cash_flow")
    capex = _latest(series, "capital_expenditures")
    revenue = _latest(series, "revenue")

    if operating_cash_flow is None or revenue is None or not shares_outstanding:
        return None

    # A bank or a REIT does not get one of these, at all.
    #
    # This model discounts unlevered free cash flow to an enterprise value
    # and then bridges to equity across net debt. For a deposit-funded
    # balance sheet that bridge is meaningless: deposits are the funding of
    # the business, not a claim to be subtracted, and such a filer tags no
    # capital expenditure, so the fallback below turned operating cash flow
    # straight into "free cash flow". The result was a bank carrying a
    # probability-weighted target at the largest type size on the page,
    # with a bear-to-bull range, and no caveat attached, because
    # `implied.caveat` had nothing to object to. A REIT is excluded for the
    # same reason in reverse: it is valued on funds from operations against
    # asset value, not on discounted enterprise cash flow.
    if sector_class in _NO_ENTERPRISE_DCF:
        return None

    # Normalised rather than latest, so one distorted year does not set the
    # base for every projected period.
    #
    # The fallback requires capital expenditure to have been filed. It used
    # to substitute `abs(capex or 0.0)`, so a filer tagging no capex had
    # operating cash flow adopted as free cash flow while the basis string
    # asserted "operating cash flow less capital expenditure", which was
    # false of that number. That is the exact substitution
    # `free_cash_flow_history` exists to refuse, and the stat strip showed
    # it plainly: "Market cap / free cash flow: NM" sat beside a modelled
    # per-share value built on the same missing figure.
    base_fcf = normalised_base_fcf(series)
    if base_fcf is None:
        if capex is None:
            return None
        base_fcf = operating_cash_flow - abs(capex)
    if base_fcf <= 0:
        return None

    measured = _cagr(series, "revenue")
    # Cap the historical rate: extrapolating an exceptional run indefinitely
    # is the most common way a DCF flatters itself.
    if measured is None:
        growth, growth_years = 0.03, 0
    else:
        growth, growth_years = measured
    growth = max(min(growth, 0.15), -0.05)

    position = net_debt(series, sector_class)
    unlevered, unlevering_basis = _unlever(series, base_fcf)

    growth_basis = (
        f"{growth_years}-year revenue CAGR from filed statements, capped at "
        f"15% and applied to free cash flow"
        if growth_years
        else "No filed growth history; 3% assumed and labelled as an assumption"
    )

    return DcfInputs(
        base_fcf=unlevered,
        fcf_growth=growth,
        discount_rate=discount_rate,
        terminal_growth=terminal_growth,
        forecast_years=forecast_years,
        net_debt=position.value,
        shares_outstanding=shares_outstanding,
        basis={
            "base_fcf": unlevering_basis,
            "fcf_growth": growth_basis,
            "discount_rate": (
                "Convention, not derived from this filer's capital structure. "
                "Replace with your own cost of capital"
            ),
            "terminal_growth": (
                "Convention, approximating long-run nominal GDP"
            ),
            "forecast_years": (
                "Ten years, which reduces the share of value resting on the "
                "terminal assumption"
            ),
            "net_debt": position.basis,
            "shares_outstanding": (
                "Diluted share count from the most recent filed period. The "
                "model holds it flat, so value per share ignores buybacks"
            ),
        },
    )


@dataclass(frozen=True)
class ValuationCase:
    name: str  # Bear, Base, Bull
    value_per_share: float
    growth: float
    discount_rate: float
    probability: float

    def upside_vs(self, price: float) -> float | None:
        if not price:
            return None
        return self.value_per_share / price - 1


def build_cases(
    inputs: DcfInputs,
    bear_growth_delta: float = -0.04,
    bull_growth_delta: float = 0.04,
    bear_wacc_delta: float = 0.02,
    bull_wacc_delta: float = -0.01,
) -> list[ValuationCase]:
    """Bear, base and bull, each a full DCF run rather than a haircut.

    The deltas are symmetric and stated, so the spread between cases reflects
    the assumptions rather than an undisclosed adjustment.
    """
    specs = [
        ("Bear", inputs.fcf_growth + bear_growth_delta,
         inputs.discount_rate + bear_wacc_delta, 0.25),
        ("Base", inputs.fcf_growth, inputs.discount_rate, 0.50),
        ("Bull", inputs.fcf_growth + bull_growth_delta,
         inputs.discount_rate + bull_wacc_delta, 0.25),
    ]
    cases = []
    for name, growth, rate, probability in specs:
        # The bull case lowers the discount rate. At a low enough starting
        # WACC that pushes it to or below terminal growth, where the Gordon
        # terminal value is infinite and run_dcf raises. The report is built
        # outside the error boundary, so an uncaught raise here killed the
        # whole run rather than one case.
        rate = max(rate, inputs.terminal_growth + 0.005)
        variant = DcfInputs(**{**inputs.__dict__, "fcf_growth": growth,
                               "discount_rate": rate})
        cases.append(
            ValuationCase(
                name=name,
                value_per_share=run_dcf(variant).value_per_share,
                growth=growth,
                discount_rate=rate,
                probability=probability,
            )
        )
    return cases


def probability_weighted_target(cases: list[ValuationCase]) -> float:
    return sum(case.value_per_share * case.probability for case in cases)


# --- implied expectations ----------------------------------------------
#
# A forward DCF on a large, highly-rated company routinely produces a value
# far below the market. Measured on Apple: a 5-year single-stage model at a
# 3.3% historical revenue CAGR and a 9% discount rate returns $103 per share
# against a $310 market price, with 74% of the value in the terminal.
#
# That is a statement about the model, not about the company. Presenting it
# as a target would be indefensible in front of anyone who values equities
# for a living.
#
# The credible form of the same analysis is to run it backwards: hold the
# market price fixed and solve for the assumption it implies. "The current
# price requires 11% annual free cash flow growth for a decade" is a claim an
# analyst can accept or reject on its merits. It is also the honest way for a
# tool to discuss valuation without asserting a target it cannot defend.

_SOLVER_TOLERANCE = 0.0001
_SOLVER_MAX_ITERATIONS = 200


@dataclass(frozen=True)
class ImpliedExpectations:
    """What the current price requires, holding everything else fixed."""

    implied_growth: float | None
    implied_discount_rate: float | None
    market_price: float
    model_value_at_defaults: float
    terminal_share: float

    @property
    def model_vs_market(self) -> float | None:
        if not self.market_price:
            return None
        return self.model_value_at_defaults / self.market_price - 1

    @property
    def caveat(self) -> str | None:
        """Stated whenever the model's own output should not be leaned on."""
        notes = []
        if self.terminal_share > 0.75:
            notes.append(
                f"{self.terminal_share:.0%} of the modelled value sits in the "
                f"terminal assumption, so the output is largely a statement "
                f"about perpetuity growth rather than about the forecast."
            )
        divergence = self.model_vs_market
        if divergence is not None and abs(divergence) > 0.4:
            notes.append(
                f"The model differs from the market by {divergence:+.0%}. A gap "
                f"of that size is more often a defect in the assumptions than a "
                f"mispricing; treat the implied expectations below as the "
                f"primary output and the target as illustrative."
            )
        return " ".join(notes) if notes else None


def _bisect(evaluate, low: float, high: float, target: float) -> float | None:
    """Solve evaluate(x) = target on a monotonic function."""
    try:
        low_value, high_value = evaluate(low), evaluate(high)
    except (ValueError, ZeroDivisionError):
        return None
    if (low_value - target) * (high_value - target) > 0:
        return None  # target not bracketed

    for _ in range(_SOLVER_MAX_ITERATIONS):
        mid = (low + high) / 2
        try:
            value = evaluate(mid)
        except (ValueError, ZeroDivisionError):
            return None
        if abs(value - target) < _SOLVER_TOLERANCE * max(target, 1.0):
            return mid
        if (value - target) * (low_value - target) > 0:
            low, low_value = mid, value
        else:
            high = mid
    return (low + high) / 2


def implied_expectations(inputs: DcfInputs, market_price: float) -> ImpliedExpectations:
    """Solve for the growth rate, and separately the discount rate, that the
    current price implies under otherwise unchanged assumptions."""
    baseline = run_dcf(inputs)

    def value_at_growth(growth: float) -> float:
        variant = DcfInputs(**{**inputs.__dict__, "fcf_growth": growth})
        return run_dcf(variant).value_per_share

    def value_at_rate(rate: float) -> float:
        variant = DcfInputs(**{**inputs.__dict__, "discount_rate": rate})
        return run_dcf(variant).value_per_share

    growth = _bisect(value_at_growth, -0.10, 0.60, market_price)
    # Discount rate must stay above terminal growth for the model to resolve.
    rate = _bisect(value_at_rate, inputs.terminal_growth + 0.005, 0.40, market_price)

    return ImpliedExpectations(
        implied_growth=growth,
        implied_discount_rate=rate,
        market_price=market_price,
        model_value_at_defaults=baseline.value_per_share,
        terminal_share=baseline.terminal_share_of_value,
    )


# --- what the market is actually paying ---------------------------------


@dataclass(frozen=True)
class CashFlowContext:
    """The cash multiple the market pays, against the growth it has seen.

    A discounted cash flow that lands far from the price prompts the obvious
    question: is the model wrong, or is the market? Neither answer is
    available from the model's output alone, but these two figures put the
    question on the table honestly.

    Measured on Apple: the market capitalises free cash flow at roughly 46
    times, on a filed record in which free cash flow compounded at 1.5% over
    five years and the most recent year came in below FY2022. That is not a
    defect in the arithmetic. It says the price rests on expectations the
    filed cash flow record does not yet contain, and it tells the reader
    exactly which expectations to interrogate.
    """

    latest_fcf: float | None
    average_fcf: float | None
    fcf_cagr: float | None
    years_observed: int
    market_cap: float | None

    @property
    def multiple_of_fcf(self) -> float | None:
        if not self.market_cap or not self.latest_fcf or self.latest_fcf <= 0:
            return None
        return self.market_cap / self.latest_fcf

    @property
    def fcf_yield(self) -> float | None:
        multiple = self.multiple_of_fcf
        return 1 / multiple if multiple else None

    def summary(self) -> str | None:
        """One sentence a reader can act on."""
        multiple = self.multiple_of_fcf
        if multiple is None or self.fcf_cagr is None:
            return None
        return (
            f"The market capitalises free cash flow at {multiple:,.0f} times, "
            f"on a filed record in which free cash flow compounded at "
            f"{self.fcf_cagr * 100:,.1f}% over {self.years_observed} years. "
            f"The price therefore rests on expectations not present in the "
            f"filed cash flow history, and those expectations are what a "
            f"reader should interrogate rather than the modelled target."
        )


def cash_flow_context(
    series: MetricSeries, market_cap: float | None
) -> CashFlowContext:
    history = free_cash_flow_history(series)
    values = [value for _, _, value in history]

    cagr = None
    years_observed = 0
    if len(history) >= 2 and values[0] > 0 and values[-1] > 0:
        elapsed = _elapsed_years(history[0][0], history[-1][0])
        if elapsed:
            cagr = (values[-1] / values[0]) ** (1 / elapsed) - 1
            years_observed = round(elapsed)

    return CashFlowContext(
        latest_fcf=values[-1] if values else None,
        average_fcf=sum(values) / len(values) if values else None,
        fcf_cagr=cagr,
        years_observed=years_observed,
        market_cap=market_cap,
    )
